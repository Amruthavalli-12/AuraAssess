const r = require('express').Router();
const c = require('../controllers/teacherController');
r.get('/dashboard', c.dashboard);
r.get('/students', c.students);
r.get('/topics', c.questions.topics);
r.get('/questions', c.questions.list);
r.post('/questions', c.questions.create);
r.put('/questions/:id', c.questions.update);
r.delete('/questions/:id', c.questions.remove);
r.get('/exams', c.exams.list);
r.post('/exams', c.exams.create);
r.get('/exams/:id', c.exams.one);
r.put('/exams/:id', c.exams.update);
r.delete('/exams/:id', c.exams.remove);
r.post('/exams/:id/assign', c.exams.assign);
r.get('/exams/:id/results', c.exams.results);
r.get('/exams/:id/ranking', c.exams.ranking);
r.get('/exams/:id/analytics', c.exams.analytics);
module.exports = r;
